/**
 * 名簿をいじって特定の1人を当てるのに、主催者が試す名簿の数の目安(期待値)。
 * 1回の試行で当たる確率は winners / N なので、平均 N / winners 回。
 */
export function stuffingAttempts(total, winners) {
  if (!(total > 0) || !(winners > 0)) return 0;
  return Math.max(1, Math.ceil(total / Math.min(winners, total)));
}
